#!/usr/bin/env node
/**
 * بررسی یکپارچگی امضای نویسنده.
 *
 * چه می‌سنجد:
 *   ۱) هر فایل PHP خط @author SparKnife دارد
 *   ۲) هیچ ایمیل شخص ثالثی در کد نیست
 *   ۳) هدر افزونه Author / copyright / license دارد
 *   ۴) LICENSE دوگانه است و ایمیل و حق نشر دارد
 *   ۵) هیچ آثار ابزار تولید کد نیست
 *   ۶) هیچ کلید خصوصی در بسته نیست
 *   ۷) هر سند docs/ امضا دارد
 *
 * اجرا: node tools/check-authorship.mjs
 * خروج ۰ = همه درست. یک = چیزی سر جایش نیست.
 */
// بررسی یکپارچگی امضای نویسنده در کل پروژه.
import fs from 'fs';
import path from 'path';
import { execSync } from 'child_process';

const root = '/home/user/SparKnife-ledger';
const plugin = path.join(root, 'sparkknife-ledger');
const AUTHOR = 'SparKnife';
const EMAIL = '155084046+sparkknife@users.noreply.github.com';
let fail = 0;
const bad = (m) => { console.log('  ✗ ' + m); fail++; };
const ok = (m) => console.log('  ✓ ' + m);

// ۱) هر فایل PHP باید @author داشته باشد
const files = execSync(`find ${plugin} -name '*.php' -type f`).toString().trim().split('\n').sort();
let noAuthor = [];
for (const f of files) {
  const src = fs.readFileSync(f, 'utf8');
  if (!/@author\s+SparKnife/.test(src)) noAuthor.push(path.relative(plugin, f));
}
if (noAuthor.length) bad(`${noAuthor.length} فایل بدون @author SparKnife: ${noAuthor.slice(0,3).join(', ')}`);
else ok(`همهٔ ${files.length} فایل PHP: @author SparKnife`);

// ۲) هیچ ایمیل شخص ثالثی در فایل‌ها نباشد
const THIRD = /@(gmail|yahoo|hotmail|outlook|protonmail)\./i;
let thirdParty = [];
for (const f of files) {
  if (THIRD.test(fs.readFileSync(f, 'utf8'))) thirdParty.push(path.relative(plugin, f));
}
if (thirdParty.length) bad(`ایمیل شخص ثالث در: ${thirdParty.join(', ')}`);
else ok('هیچ ایمیل شخص ثالثی در کد نیست');

// ۳) هدر افزونه امضا داشته باشد
const main = fs.readFileSync(path.join(plugin, 'sparkknife-ledger.php'), 'utf8');
const checks = [
  [/^\s*\*\s*Author:\s+SparKnife/m, 'هدر: Author SparKnife'],
  [/@author\s+SparKnife/, 'هدر: @author SparKnife'],
  [/@copyright\s+2026 SparKnife/, 'هدر: @copyright'],
  [/@license\s+.*(GPL|commercial)/i, 'هدر: @license دوگانه'],
];
for (const [re, label] of checks) {
  if (re.test(main)) ok(label); else bad(label + ' پیدا نشد');
}

// ۴) LICENSE موجود و دوگانه باشد
const lic = path.join(plugin, 'LICENSE');
if (fs.existsSync(lic)) {
  const s = fs.readFileSync(lic, 'utf8');
  if (/GPL-2\.0-or-later/.test(s) && /لایسنس تجاری|commercial/i.test(s)) ok('LICENSE: دوگانه (GPL + تجاری)');
  else bad('LICENSE دوگانه نیست');
  if (s.includes(EMAIL)) ok('LICENSE: ایمیل نویسنده'); else bad('LICENSE: ایمیل نیست');
  if (/copyright|حق نشر/i.test(s)) ok('LICENSE: حق نشر'); else bad('LICENSE: حق نشر نیست');
} else bad('LICENSE وجود ندارد');

// ۵) آثار ابزار
const TOOL = /\b(chatgpt|openai|anthropic|claude|copilot|generated by ai|as an ai)\b/i;
let found = [];
const allFiles = execSync(`find ${plugin} -type f \\( -name '*.php' -o -name '*.js' -o -name '*.css' -o -name '*.txt' \\)`).toString().trim().split('\n');
for (const f of allFiles) {
  const rel = path.relative(plugin, f);
  const s = fs.readFileSync(f, 'utf8');
  if (TOOL.test(s)) found.push(rel);
}
if (found.length) bad(`آثار ابزار در: ${found.join(', ')}`);
else ok('هیچ آثار ابزار (chatgpt/claude/copilot) نیست');

// ۶) هیچ کلید خصوصی در بسته
const keys = execSync(`find ${plugin} -name '*.pem' -o -name '*.key' 2>/dev/null || true`).toString().trim();
if (keys) bad(`فایل کلید در بسته: ${keys}`); else ok('هیچ فایل کلید خصوصی در بسته');

// ۷) اسناد امضا دارند
let noSign = [];
for (const d of fs.readdirSync(path.join(root, 'docs'))) {
  if (!d.endsWith('.md')) continue;
  const s = fs.readFileSync(path.join(root, 'docs', d), 'utf8');
  if (!/SparKnife/.test(s.slice(-400))) noSign.push(d);
}
if (noSign.length) bad(`سند بدون امضا: ${noSign.join(', ')}`);
else ok('همهٔ اسناد docs/ امضای SparKnife دارند');

console.log('');
if (fail) { console.log(`${fail} بررسی ناموفق ✗`); process.exit(1); }
console.log('همهٔ بررسی‌های نویسندگی موفق ✓');
